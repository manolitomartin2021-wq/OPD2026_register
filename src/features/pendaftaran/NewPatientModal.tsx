import React, { useState } from 'react';
import type { Citizenship, DocumentType, Gender, Patient } from '../../types';
import { createNewPatient } from '../../data/dataService';
import { UserPlus, X, AlertTriangle, CheckCircle, Sparkles, Calendar, ShieldCheck } from 'lucide-react';
import { parseMyKad } from '../../utils/normalize';
import { calculateAge, formatDateDisplay } from '../../utils/dateUtils';

interface NewPatientModalProps {
  isOpen: boolean;
  onClose: () => void;
  onPatientCreated: (patient: Patient) => void;
  initialQuery?: string;
}

export const NewPatientModal: React.FC<NewPatientModalProps> = ({
  isOpen,
  onClose,
  onPatientCreated,
  initialQuery = '',
}) => {
  const [kewarganegaraan, setKewarganegaraan] = useState<Citizenship>('WARGANEGARA');
  const [jenisDokumen, setJenisDokumen] = useState<DocumentType>('MYKAD');
  const [noDokumen, setNoDokumen] = useState(initialQuery);
  const [noPasport, setNoPasport] = useState('');
  const [namaPesakit, setNamaPesakit] = useState('');
  const [jantina, setJantina] = useState<Gender>('LELAKI');
  const [tarikhLahir, setTarikhLahir] = useState('');
  const [etnik, setEtnik] = useState('MELANAU');
  const [alamat, setAlamat] = useState('');
  const [nomborTelefon, setNomborTelefon] = useState('');

  // Penunjuk status auto-generate dari MyKad
  const [isMyKadAutoGenerated, setIsMyKadAutoGenerated] = useState(false);

  const [errorMsg, setErrorMsg] = useState('');
  const [loading, setLoading] = useState(false);

  if (!isOpen) return null;

  // Auto-generate Jantina, Tarikh Lahir, dan Umur daripada MyKad (12 Digit)
  const handleDocChange = (val: string) => {
    setNoDokumen(val);
    if (kewarganegaraan === 'WARGANEGARA' && (jenisDokumen === 'MYKAD' || jenisDokumen === 'MYKID')) {
      const parsed = parseMyKad(val);
      if (parsed.isValid && parsed.birthDate && parsed.gender) {
        setTarikhLahir(parsed.birthDate);
        setJantina(parsed.gender);
        setIsMyKadAutoGenerated(true);
        return;
      }
    }
    setIsMyKadAutoGenerated(false);
  };

  const calculatedAge = tarikhLahir ? calculateAge(tarikhLahir) : null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMsg('');

    if (!namaPesakit.trim()) {
      setErrorMsg('Nama pesakit adalah WAJIB diisi.');
      return;
    }
    if (!tarikhLahir) {
      setErrorMsg('Tarikh lahir adalah WAJIB diisi.');
      return;
    }

    if (kewarganegaraan === 'BUKAN WARGANEGARA' && !noPasport.trim()) {
      setErrorMsg('No. Pasport adalah WAJIB bagi pesakit Bukan Warganegara.');
      return;
    }

    if (kewarganegaraan === 'WARGANEGARA' && jenisDokumen !== 'TIADA DOKUMEN' && !noDokumen.trim()) {
      setErrorMsg('No. Dokumen adalah WAJIB bagi pesakit Warganegara (kecuali bayi berstatus TIADA DOKUMEN).');
      return;
    }

    setLoading(true);
    try {
      const newPatient = await createNewPatient({
        kewarganegaraan,
        jenis_dokumen: jenisDokumen,
        no_dokumen: noDokumen,
        no_pasport: noPasport,
        nama_pesakit: namaPesakit,
        jantina,
        tarikh_lahir: tarikhLahir,
        etnik,
        alamat,
        nombor_telefon: nomborTelefon,
        nama_waris: '', // Dihapuskan mengikut arahan
        telefon_waris: '', // Dihapuskan mengikut arahan
      });

      onPatientCreated(newPatient);
      onClose();
    } catch (err: any) {
      setErrorMsg(err.message || 'Ralat semasa mendaftar pesakit baharu.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 overflow-y-auto">
      <div className="w-full max-w-2xl bg-white rounded-3xl shadow-2xl border-2 border-gray-300 overflow-hidden my-6">
        <div className="p-6 bg-[#2F5D8A] text-white flex justify-between items-center">
          <div className="flex items-center gap-3">
            <UserPlus className="w-8 h-8 text-white" />
            <div>
              <h2 className="text-2xl font-black">DAFTAR PESAKIT BAHARU</h2>
              <p className="text-sm text-blue-100 font-medium">
                No. RN akan dijana secara automatik (HD-RN/YYYY/NNNN)
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl text-white hover:bg-white/20 transition cursor-pointer"
          >
            <X className="w-7 h-7" />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="p-6 md:p-8 space-y-6">
          {errorMsg && (
            <div className="p-4 bg-red-50 border-2 border-[#991B1B] text-[#991B1B] rounded-xl font-bold flex items-center gap-3">
              <AlertTriangle className="w-6 h-6 flex-shrink-0" />
              <span>{errorMsg}</span>
            </div>
          )}

          {/* Citizenship Choice */}
          <div>
            <label className="block text-base font-black text-gray-900 mb-2">
              KEWARGANEGARAAN (WAJIB PILIH DAHULU):
            </label>
            <div className="grid grid-cols-2 gap-4">
              <button
                type="button"
                onClick={() => setKewarganegaraan('WARGANEGARA')}
                className={`py-4 px-6 rounded-2xl font-black text-lg border-3 transition flex items-center justify-center gap-2 cursor-pointer ${
                  kewarganegaraan === 'WARGANEGARA'
                    ? 'border-[#2F5D8A] bg-blue-50 text-[#2F5D8A] ring-2 ring-blue-300 shadow-md'
                    : 'border-gray-300 bg-white text-gray-700 hover:bg-gray-50'
                }`}
              >
                <CheckCircle
                  className={`w-6 h-6 ${kewarganegaraan === 'WARGANEGARA' ? 'text-[#2F5D8A]' : 'opacity-20'}`}
                />
                <span>WARGANEGARA</span>
              </button>

              <button
                type="button"
                onClick={() => setKewarganegaraan('BUKAN WARGANEGARA')}
                className={`py-4 px-6 rounded-2xl font-black text-lg border-3 transition flex items-center justify-center gap-2 cursor-pointer ${
                  kewarganegaraan === 'BUKAN WARGANEGARA'
                    ? 'border-[#9A6014] bg-amber-50 text-[#9A6014] ring-2 ring-amber-300 shadow-md'
                    : 'border-gray-300 bg-white text-gray-700 hover:bg-gray-50'
                }`}
              >
                <CheckCircle
                  className={`w-6 h-6 ${kewarganegaraan === 'BUKAN WARGANEGARA' ? 'text-[#9A6014]' : 'opacity-20'}`}
                />
                <span>BUKAN WARGANEGARA</span>
              </button>
            </div>
          </div>

          {/* Conditional ID Fields */}
          {kewarganegaraan === 'WARGANEGARA' ? (
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div>
                <label className="block text-base font-bold text-gray-800 mb-1">
                  Jenis Dokumen:
                </label>
                <select
                  value={jenisDokumen}
                  onChange={(e) => {
                    const newType = e.target.value as DocumentType;
                    setJenisDokumen(newType);
                    if (newType === 'MYKAD' || newType === 'MYKID') {
                      handleDocChange(noDokumen);
                    }
                  }}
                  className="w-full p-3.5 rounded-xl border-2 border-gray-400 font-bold text-base focus:outline-none focus:border-[#2F5D8A]"
                >
                  <option value="MYKAD">MYKAD (Kad Pengenalan Awam)</option>
                  <option value="MYKID">MYKID (Kanak-kanak)</option>
                  <option value="MYPR">MYPR (Penduduk Tetap)</option>
                  <option value="POLIS/TENTERA">POLIS / TENTERA</option>
                  <option value="TIADA DOKUMEN">TIADA DOKUMEN (Bayi Baru Lahir)</option>
                </select>
              </div>

              <div>
                <label className="block text-base font-bold text-gray-800 mb-1">
                  Nombor MyKad / MyKid:
                </label>
                <input
                  type="text"
                  value={noDokumen}
                  disabled={jenisDokumen === 'TIADA DOKUMEN'}
                  onChange={(e) => handleDocChange(e.target.value)}
                  placeholder={
                    jenisDokumen === 'TIADA DOKUMEN'
                      ? 'Tidak diperlukan untuk bayi baru lahir'
                      : 'cth: 900101-13-1234 atau 900101131234'
                  }
                  className="w-full p-3.5 rounded-xl border-2 border-gray-400 font-bold text-base focus:outline-none focus:border-[#2F5D8A] disabled:bg-gray-100"
                />
              </div>
            </div>
          ) : (
            <div>
              <label className="block text-base font-bold text-gray-800 mb-1">
                Nombor Pasport (WAJIB bagi Bukan Warganegara):
              </label>
              <input
                type="text"
                value={noPasport}
                onChange={(e) => setNoPasport(e.target.value.toUpperCase())}
                placeholder="cth: A12345678"
                className="w-full p-3.5 rounded-xl border-2 border-gray-400 font-bold text-base uppercase focus:outline-none focus:border-[#9A6014]"
              />
            </div>
          )}

          {/* Auto-Generation Badge from MyKad */}
          {isMyKadAutoGenerated && calculatedAge && (
            <div className="p-3 bg-emerald-50 border-2 border-emerald-400 text-emerald-900 rounded-xl flex items-center justify-between gap-3 text-sm font-bold animate-in fade-in">
              <div className="flex items-center gap-2">
                <Sparkles className="w-5 h-5 text-emerald-600 flex-shrink-0" />
                <span>
                  Dijana Automatik dari MyKad: <strong>{jantina}</strong> · Lahir: <strong>{formatDateDisplay(tarikhLahir)}</strong> · Umur: <strong>{calculatedAge.display}</strong>
                </span>
              </div>
              <span className="px-2 py-0.5 bg-emerald-200 text-emerald-900 rounded text-xs font-black">
                AUTO-FILL
              </span>
            </div>
          )}

          {/* Patient Name */}
          <div>
            <label className="block text-base font-bold text-gray-800 mb-1">
              Nama Pesakit Penuh (Automatik Huruf Besar):
            </label>
            <input
              type="text"
              value={namaPesakit}
              onChange={(e) => setNamaPesakit(e.target.value.toUpperCase())}
              placeholder="cth: MANOLITO MARTIN ANAK RICKY"
              className="w-full p-3.5 rounded-xl border-2 border-gray-400 font-black text-lg uppercase focus:outline-none focus:border-[#2F5D8A]"
            />
          </div>

          {/* Gender & Birth Date & Auto-Generated Age */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div>
              <label className="block text-base font-bold text-gray-800 mb-1">
                Jantina {isMyKadAutoGenerated && <span className="text-emerald-700 text-xs font-bold">(Auto dari MyKad)</span>}:
              </label>
              <div className="grid grid-cols-2 gap-3">
                <button
                  type="button"
                  onClick={() => setJantina('LELAKI')}
                  className={`py-3 rounded-xl font-bold border-2 cursor-pointer ${
                    jantina === 'LELAKI'
                      ? 'border-[#2F5D8A] bg-blue-100 text-[#2F5D8A] font-black shadow-sm'
                      : 'border-gray-300 bg-white text-gray-700 hover:bg-gray-50'
                  }`}
                >
                  LELAKI
                </button>
                <button
                  type="button"
                  onClick={() => setJantina('PEREMPUAN')}
                  className={`py-3 rounded-xl font-bold border-2 cursor-pointer ${
                    jantina === 'PEREMPUAN'
                      ? 'border-[#2F5D8A] bg-blue-100 text-[#2F5D8A] font-black shadow-sm'
                      : 'border-gray-300 bg-white text-gray-700 hover:bg-gray-50'
                  }`}
                >
                  PEREMPUAN
                </button>
              </div>
            </div>

            <div>
              <label className="block text-base font-bold text-gray-800 mb-1">
                Tarikh Lahir:
              </label>
              <input
                type="date"
                value={tarikhLahir}
                onChange={(e) => setTarikhLahir(e.target.value)}
                className="w-full p-3.5 rounded-xl border-2 border-gray-400 font-bold text-base focus:outline-none focus:border-[#2F5D8A]"
              />

              {/* Paparan Umur Jelas & Automatik */}
              {calculatedAge ? (
                <div className="mt-2 p-3 bg-blue-50 border-2 border-[#2F5D8A] rounded-xl flex items-center justify-between">
                  <span className="text-xs font-black uppercase text-gray-600 tracking-wider">
                    PAPARAN UMUR:
                  </span>
                  <span className="text-xl font-black text-[#2F5D8A] uppercase tracking-wide">
                    {calculatedAge.display.toUpperCase()} ({calculatedAge.years} TAHUN)
                  </span>
                </div>
              ) : (
                <div className="mt-2 text-xs font-bold text-gray-500">
                  (Sila masukkan tarikh lahir atau MyKad untuk paparan umur automatik)
                </div>
              )}
            </div>
          </div>

          {/* Ethnic (Ubah Orang Ulu -> Bumiputera Sarawak & Tambah Bumiputera Sabah) & Phone */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div>
              <label className="block text-base font-bold text-gray-800 mb-1">
                Etnik / Kumpulan Bangsa:
              </label>
              <select
                value={etnik}
                onChange={(e) => setEtnik(e.target.value)}
                className="w-full p-3.5 rounded-xl border-2 border-gray-400 font-bold text-base focus:outline-none focus:border-[#2F5D8A]"
              >
                <option value="MELANAU">MELANAU (Tempatan Dalat / Sarawak)</option>
                <option value="IBAN">IBAN</option>
                <option value="BUMIPUTERA SARAWAK">BUMIPUTERA SARAWAK (Peribumi Sarawak Lain / Kayan / Kenyah dsb.)</option>
                <option value="BUMIPUTERA SABAH">BUMIPUTERA SABAH (Kadazan / Dusun / Murut / Bajau / Peribumi Sabah Lain)</option>
                <option value="MELAYU">MELAYU</option>
                <option value="CINA">CINA</option>
                <option value="BIDAYUH">BIDAYUH</option>
                <option value="KADAZAN">KADAZAN</option>
                <option value="MURUT">MURUT</option>
                <option value="BAJAU">BAJAU</option>
                <option value="ORANG ASLI SEMENANJUNG">ORANG ASLI SEMENANJUNG</option>
                <option value="INDIA">INDIA</option>
                <option value="LAIN-LAIN">LAIN-LAIN</option>
              </select>
            </div>

            <div>
              <label className="block text-base font-bold text-gray-800 mb-1">
                Nombor Telefon Pesakit:
              </label>
              <input
                type="text"
                value={nomborTelefon}
                onChange={(e) => setNomborTelefon(e.target.value)}
                placeholder="cth: 013-8889999"
                className="w-full p-3.5 rounded-xl border-2 border-gray-400 font-bold text-base focus:outline-none focus:border-[#2F5D8A]"
              />
            </div>
          </div>

          {/* Address (Automatik Huruf Besar) */}
          <div>
            <label className="block text-base font-bold text-gray-800 mb-1">
              Alamat Kediaman (Automatik Huruf Besar):
            </label>
            <input
              type="text"
              value={alamat}
              onChange={(e) => setAlamat(e.target.value.toUpperCase())}
              placeholder="CTH: KAMPUNG TELLIAN TENGAH, DALAT"
              className="w-full p-3.5 rounded-xl border-2 border-gray-400 font-bold text-base uppercase focus:outline-none focus:border-[#2F5D8A]"
            />
          </div>

          {/* Action buttons */}
          <div className="pt-4 flex flex-col sm:flex-row justify-end gap-3 border-t border-gray-200">
            <button
              type="button"
              onClick={onClose}
              className="py-3 px-6 rounded-xl font-bold text-base bg-gray-200 hover:bg-gray-300 text-gray-800 transition cursor-pointer"
            >
              BATAL
            </button>
            <button
              type="submit"
              disabled={loading}
              className="py-3 px-8 rounded-xl font-black text-lg bg-[#2F5D8A] hover:bg-[#254A6F] text-white flex items-center justify-center gap-2 shadow-lg transition disabled:opacity-50 cursor-pointer"
            >
              <CheckCircle className="w-6 h-6" />
              <span>{loading ? 'MENYIMPAN...' : 'SIMPAN & TERUSKAN DAFTAR'}</span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
